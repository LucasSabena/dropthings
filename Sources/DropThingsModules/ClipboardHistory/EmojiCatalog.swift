public extension EmojiCatalog {
    /// Filter the catalog by a query. Empty query returns everything. Matching
    /// is case-insensitive against name and keywords.
    static func search(_ query: String) -> [EmojiEntry] {
        let q = query.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil).trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return entries }
        return entries.filter { entry in
            if entry.name.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil).contains(q) { return true }
            return entry.keywords.contains(where: { $0.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil).contains(q) })
        }
    }

    /// Group entries by category, preserving the `EmojiCategory` order. Empty
    /// categories are omitted so the UI has no empty sections.
    static func grouped(_ entries: [EmojiEntry]) -> [(EmojiCategory, [EmojiEntry])] {
        EmojiCategory.allCases.compactMap { category in
            let items = entries.filter { $0.category == category }
            return items.isEmpty ? nil : (category, items)
        }
    }
}

import Foundation

/// A static, searchable emoji catalog for the Emojis tab. Data is embedded so
/// there are no external files to ship; it is small enough to fit in memory.
/// Searching matches name and keywords, case-insensitive, accent-insensitive.
public struct EmojiEntry: Identifiable, Hashable, Sendable {
    public let id: String          // the glyph itself is unique
    public let glyph: String
    public let name: String
    public let keywords: [String]
    public let category: EmojiCategory

    public init(glyph: String, name: String, keywords: [String], category: EmojiCategory) {
        self.id = glyph
        self.glyph = glyph
        self.name = name
        self.keywords = keywords
        self.category = category
    }
}

